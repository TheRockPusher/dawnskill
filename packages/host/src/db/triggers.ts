/**
 * Database backstop for the kernel (PLAN.md §5): SQL generated from the transition tables in
 * `@dawnskill/core`. `scripts/gen-triggers.ts` writes the output to generated-triggers.sql (committed;
 * CI fails on drift) and every database open reinstalls it, so the triggers always match the tables.
 */
import { join } from "node:path";
import type { Completion } from "@dawnskill/core";
import { PROPOSAL_STATUS_EDGES, TASK_STATUS_EDGES } from "@dawnskill/core";

export const TRIGGERS_SQL_PATH = join(import.meta.dirname, "generated-triggers.sql");

/** Status columns guarded by a kernel transition table. */
const MACHINES: ReadonlyArray<{
	readonly entity: string;
	readonly table: string;
	readonly edges: ReadonlyArray<readonly [string, string]>;
}> = [
	{ entity: "task", table: "tasks", edges: TASK_STATUS_EDGES },
	{ entity: "proposal", table: "proposals", edges: PROPOSAL_STATUS_EDGES },
];

/** Statuses that close a task; entering one needs the completion row written in the same step (K2). */
const CLOSED = ["done", "cancelled"] as const satisfies readonly Completion["status"][];

function quote(value: string): string {
	return `'${value.replaceAll("'", "''")}'`;
}

export function generateTriggerSql(): string {
	const closed = CLOSED.map(quote).join(", ");
	/** Each aborts its statement with `message` when `when` holds. */
	const triggers: ReadonlyArray<{
		readonly name: string;
		readonly on: string;
		readonly when: string;
		readonly message: string;
	}> = [
		...MACHINES.map(({ entity, table, edges }) => ({
			name: `${entity}_status_transition`,
			on: `BEFORE UPDATE OF status ON ${table}`,
			// Rewriting the same status is not a transition.
			when: `NEW.status IS NOT OLD.status\n\tAND (OLD.status, NEW.status) NOT IN (VALUES ${edges.map(([from, to]) => `(${quote(from)}, ${quote(to)})`).join(", ")})`,
			message: `'illegal ${entity} transition ' || OLD.status || '->' || NEW.status`,
		})),
		{
			name: "task_close_needs_completion",
			on: "BEFORE UPDATE OF status ON tasks",
			when: `NEW.status IN (${closed}) AND NEW.status IS NOT OLD.status AND NOT EXISTS (
	SELECT 1 FROM completions c
	WHERE c.id = (SELECT max(id) FROM completions WHERE task_id = NEW.id)
		AND c.status = NEW.status AND c.at = NEW.updated_at
)`,
			message: `'task ' || NEW.id || ' entering ' || NEW.status || ' needs its latest completion row (' || NEW.status || ' at ' || NEW.updated_at || ')'`,
		},
		{
			name: "skill_insert_unrated",
			on: "BEFORE INSERT ON skills",
			when: "NEW.level IS NOT NULL",
			message: `'skill ' || NEW.key || ' must be inserted unrated; a level arrives only by update with an assessment'`,
		},
		{
			name: "skill_level_needs_assessment",
			on: "BEFORE UPDATE OF level ON skills",
			when: `NEW.level IS NOT OLD.level AND NOT EXISTS (
	SELECT 1 FROM assessments a
	WHERE a.id = (SELECT max(id) FROM assessments WHERE skill = NEW.key)
		AND a.level = NEW.level AND a.at = NEW.level_at
)`,
			message: `'skill ' || NEW.key || ' level ' || quote(OLD.level) || '->' || quote(NEW.level) || ' needs its latest assessment row (level ' || quote(NEW.level) || ' at ' || quote(NEW.level_at) || ')'`,
		},
		{
			name: "dependency_insert_open_tasks",
			on: "BEFORE INSERT ON dependencies",
			when: `EXISTS (SELECT 1 FROM tasks WHERE id IN (NEW.task_id, NEW.blocker_id) AND status IN (${closed}))`,
			message: `'dependency ' || NEW.blocker_id || ' blocks ' || NEW.task_id || ' touches a closed task'`,
		},
		{
			name: "dependency_delete_open_tasks",
			on: "BEFORE DELETE ON dependencies",
			when: `EXISTS (SELECT 1 FROM tasks WHERE id IN (OLD.task_id, OLD.blocker_id) AND status IN (${closed}))`,
			message: `'dependency ' || OLD.blocker_id || ' blocks ' || OLD.task_id || ' touches a closed task; closing keeps edges (K7)'`,
		},
	];
	const rows = MACHINES.flatMap(({ entity, edges }) =>
		edges.map(([from, to]) => `\t(${quote(entity)}, ${quote(from)}, ${quote(to)})`),
	);
	const sections = [
		`-- Generated by scripts/gen-triggers.ts from TASK_STATUS_EDGES and PROPOSAL_STATUS_EDGES in @dawnskill/core.
-- Do not edit: run \`pnpm triggers:gen\`. Reinstalled on every database open.`,
		triggers.map(({ name }) => `DROP TRIGGER IF EXISTS ${name};`).join("\n"),
		`DELETE FROM allowed_transitions;\nINSERT INTO allowed_transitions (entity, from_status, to_status) VALUES\n${rows.join(",\n")};`,
		...triggers.map(
			({ name, on, when, message }) =>
				`CREATE TRIGGER ${name}\n${on}\nWHEN ${when}\nBEGIN\n\tSELECT RAISE(ABORT, ${message});\nEND;`,
		),
	];
	return `${sections.join("\n\n")}\n`;
}
